def current_lang():
    from flask import g

    forced = g.get("force_lang") if g else None
    if forced in LANGS:
        return forced
    lang = session.get("lang")
    if lang in LANGS:
        return lang
    return DEFAULT_LANG  # Arabic unless the user switches language


from .i18n_extra import EXTRA  # noqa: E402

TEXT.update(EXTRA)


def t(key, **kwargs):
    entry = TEXT.get(key)
    if entry is None:
        return key
    lang = current_lang()
    from .settings import label_override

    text = label_override(key, lang) or (entry[1] if lang == "ar" else entry[0])
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text
    return text
